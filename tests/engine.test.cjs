const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const path=require('node:path');
const E=require('../dist/engine.js');
const ctx={window:{}};
vm.runInNewContext(fs.readFileSync(path.join(__dirname,'../dist/data.js'),'utf8'),ctx);
const D=JSON.parse(JSON.stringify(ctx.window.ND_DATA));
const c=E.clone(D.initial);
assert.equal(E.derive(c,D.catalog).maxHP,5);
assert.equal(E.derive(c,D.catalog).skillPoints,-1);
assert.equal(E.derive(c,D.catalog).freeChrome,7);
assert.equal(E.derive(c,D.catalog).currentArmor,1);
assert.equal(E.derive(c,D.catalog).validAttributes,true);
c.attributes[0]=0;c.hp=3;c.attributes[2]=2;
assert.equal(E.derive(c,D.catalog).maxHP,3);
assert.equal(E.derive(c,D.catalog).skillPoints,1);
const heavy=D.catalog.implants.find(x=>x.slots===3);
c.implants[0].name=heavy.name;c.implants[1].name=heavy.name;
assert.equal(E.derive(c,D.catalog).freeChrome,-3);
assert.equal(E.derive(c,D.catalog).psychosis,3);
c.armor=D.catalog.armor.find(x=>x.armor===2).name;c.armorSpent=1;
assert.equal(E.derive(c,D.catalog).currentArmor,1);
assert.deepEqual(E.validate(c,D),c);
assert.throws(()=>E.validate({...c,skills:[99]},D));
assert.throws(()=>E.validate({...c,hp:100},D));
assert.throws(()=>E.validate({...c,money:-1},D));
assert.throws(()=>E.validate({...c,weapons:['unknown','']},D));
assert.throws(()=>E.validate({...c,notes:[{location:null,npc:'',text:''}]},D));
assert.equal(D.catalog.weapons.length,14);
assert.equal(D.catalog.implants.length,18);
assert.equal(D.catalog.consumables.length,18);
for(const group of Object.values(D.catalog))assert.equal(new Set(group.map(x=>x.name)).size,group.length);
console.log('PASS: initial sheet calculations, changed attributes, chrome overload, armor damage, import validation and catalog integrity.');
